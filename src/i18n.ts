export function translator(locale: Locale) {
  return (key: Key): string => (locale === "el" ? el : en)[key];
}
export type Translate = ReturnType<typeof translator>;
export function money(cents: number,locale: Locale): string {
  return new Intl.NumberFormat(locale === "el" ? "el-CY" : "en-IE",{
    style: "currency",
    currency: "EUR",
  }).format(cents / 100);
}
export function dateLabel(date: string,locale: Locale): string {
  return new Intl.DateTimeFormat(locale === "el" ? "el-CY" : "en-GB",{
    day: "2-digit",
    month: "short",
    year: "numeric",
    timeZone: "Asia/Nicosia",
  }).format(new Date(`${date}T12:00:00Z`));
}
export function cyprusToday(now = new Date()): string {
  const parts = new Intl.DateTimeFormat("en-GB",{
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
    timeZone: "Asia/Nicosia",
  }).formatToParts(now);
  return ["year","month","day"]
    .map((type) => parts.find((p) => p.type === type)?.value)
    .join("-");
}

export function monthLabel(month: string,locale: Locale): string {
  return new Intl.DateTimeFormat(locale === "el" ? "el-CY" : "en-GB",{
    month: "long",
    year: "numeric",
    timeZone: "UTC",
  }).format(new Date(`${month}-01T12:00:00Z`));
}
